import os
from pathlib import Path
from dotenv import load_dotenv
from groq import Groq
from time import sleep

# Load environment variables from the .env file.
# This allows us to access our Groq API key without hardcoding it.
load_dotenv()

# Get the API key stored in the .env file.
my_api_key = os.getenv("GROQ_API_KEY")

# Stop the program if the API key is missing.
if not my_api_key:
    raise ValueError("API key kaha hai bhai")

# Create a Groq client to communicate with the LLM.
client = Groq(api_key=my_api_key)

# Specify which LLM we want to use for our tasks.
model = "qwen/qwen3.8-27b"


# Job description: Contains the skills and experience required for the role.
JD = """
We are hiring a Backend Python Developer.

Requirements:
- Strong Python
- FastAPI or Django
- PostgreSQL
- Docker
- AWS
- REST APIs
- 2+ years of experience
"""

# Resume: Contains the candidate's skills, experience, and projects.
RESUME = """
Name: Rahul Sharma

Experience:
3 years as a Software Developer.

Skills:
Python, FastAPI, MySQL, Docker,
REST APIs, Git

Projects:
Built a food delivery backend using
FastAPI and MySQL.

Deployed applications using Docker.
"""


def ask_llm(system_prompt, user_prompt):
    # The system prompt tells the LLM its role and how it should respond.
    sys_msg = {
        "role": "system",
        "content": system_prompt
    }

    # The user prompt contains the actual task and the information to analyze.
    user_msg = {
        "role": "user",
        "content": user_prompt
    }

    # Send both messages together to the LLM.
    # The system message provides instructions, and the user message provides input.
    messages = [sys_msg, user_msg]

    # Send the request to Groq and wait for the LLM's response.
    response = client.chat.completions.create(
        model=model,
        messages=messages
    )

    # Extract the actual text generated by the LLM from the API response.
    answer = response.choices[0].message.content

    # Return the generated text so the calling function can use it.
    return answer


def step1_res_extract(RESUME):
    print("STEP-1")

    # Tell the LLM to act as an HR assistant and extract only the candidate's skills.
    # The LLM must not add skills that are not present in the resume.
    system_prompt = """
    You are a professional HR assistant. Extract the skills from the candidates resume provided.
    Only return the skills no other information. Do not invent any skills by yourself.
    Output Format:
    Skills should be separated by commas. Just return comma separated skills do not return any other filler information
    """

    # Pass the resume to the LLM and ask it to extract the skills.
    user_prompt = f"""
    Extract the skills from this resume
    {RESUME}
    """

    # Return the extracted skills to the main program.
    return ask_llm(system_prompt, user_prompt)


def step2_JD_extract(JD):
    print("STEP-2")

    # Tell the LLM to extract the skills required by the job description.
    # This helps us identify what the employer expects from a candidate.
    system_prompt = """
    You are a professional HR assistant. Extract the skills from the Job description provided.
    Only return the skills no other information. Do not invent any skills by yourself.
    Output Format:
    Skills should be separated by commas. Just return comma separated skills do not return any other filler information
    """

    # Pass the job description to the LLM and ask it to extract the required skills.
    user_prompt = f"""
    Extract the skills from this JD
    {JD}
    """

    # Return the extracted job requirements to the main program.
    return ask_llm(system_prompt, user_prompt)


def step3_match(candidate, jd):
    print("STEP-3")

    # Tell the LLM to compare the candidate's skills with the job requirements.
    # It must provide a score between 1 and 100 and a short hiring-fit verdict.
    system_prompt = """
    You are a professional HR assistant. Compare the skills of the candidate
    with the skills required in the JD and produce a final score between
    1 and 100. Also produce a short verdict on whether the candidate is a good fit for the role.
    """

    # Give the LLM both sets of skills so it can compare them.
    user_prompt = f"""
    Compare and match the skills.

    JD:
    {jd}

    Candidate:
    {candidate}
    """

    # Return the LLM's comparison, score, and verdict.
    return ask_llm(system_prompt, user_prompt)


# STEP 1: Extract the candidate's skills from the resume.
candidate = step1_res_extract(RESUME)
print(candidate)

# Pause for 2 seconds before making the next API request.
sleep(2)

# STEP 2: Extract the skills required by the job description.
jd = step2_JD_extract(JD)
print(jd)

# Pause for 2 seconds before making the next API request.
sleep(2)

# STEP 3: Compare the candidate's skills against the job requirements.
score = step3_match(candidate, jd)
print(score)


